const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'..','crm.html'),'utf8');
const c={itemPatch:()=>({}),inquiryCreatedAt:x=>x.created,stageLabel:x=>x,dealStage:()=> 'waiting',isWon:()=>false,isOpen:()=>true,peopleStore:()=>({}),DataCleanupUI:{historyFor:()=>[]},ExpansionPool:{historyFor:()=>[]},siteStamp:x=>Date.parse(x)||0};
vm.createContext(c);c.siteNoteDisplayText=x=>x;vm.runInContext(src.split(/\r?\n/).filter(x=>x.startsWith('function siteTimeline(')||x.startsWith('function siteActivityTitle(')).join('\n'),c);
const activities=Array.from({length:24},(_,i)=>({type:'전화',note:'기록 '+i,occurred_at:`2023-${String(i%12+1).padStart(2,'0')}-01T10:00:00Z`,created_at:'2026-09-15T10:00:00Z'}));
const site={inquiries:[],deals:[{activities}],norm:'sample'};
const before=JSON.stringify(site),rows=c.siteTimeline(site);
assert.equal(rows.length,24,'Do not truncate loaded history at 16');
assert.ok(rows.every(x=>x.at.startsWith('2023-')),'Prefer actual occurrence over import/entry date');
assert.ok(rows.every((x,i)=>!i||Date.parse(rows[i-1].at)>=Date.parse(x.at)),'Newest first');
assert.equal(JSON.stringify(site),before,'Do not mutate source records');
console.log('Full loaded history, occurrence time, sort and source preservation passed');
const note={id:'original-note',body:'<script>untrusted</script>',actor:'기록자',occurred_at:'2024-01-01',recorded_at:'2026-09-15'};
const noteRows=c.siteTimeline({inquiries:[],deals:[{legacy_notes:[note]},{legacy_notes:[note,{...note,id:'different-note'}]}]});
assert.equal(noteRows.length,2,'Deduplicate same original ID across deals, retain different IDs');
assert.equal(noteRows[0].recordedAt,'2026-09-15');
assert.equal(noteRows[0].at,'2024-01-01');
assert.equal(noteRows[0].sub,note.body,'Keep source text for existing escaped renderer');
assert.ok(src.includes("esc(e.sub)"),'Existing renderer escapes note body');
console.log('Legacy note identity, original dates and escaped renderer checks passed');
